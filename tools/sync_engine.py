"""Copy the recommendation engine out of the team's 06_recommend notebook into engine/recommend_engine.py.

Run before every deploy:  python tools/sync_engine.py
Keeps only the function cells (Config → Step 6); drops demos, scenario tests, sensitivity check, summary.
The teammate's code is copied unchanged; the app supplies `spark` (Databricks Connect) and can switch
off the engine's table writes (see engine/__init__.py).
"""
import ast, pathlib, re, subprocess, sys, tempfile

NOTEBOOK = "/Workspace/Shared/Datathon 2026/06_recommend"
KEEP = re.compile(r"^(Config|resolve_service|Step 1|Step 2|Step 3|Steps 4\+5|Step 6)\b")
OUT = pathlib.Path(__file__).resolve().parents[1] / "engine" / "recommend_engine.py"

arg = sys.argv[1] if len(sys.argv) > 1 else ""
if arg.endswith(".py") and pathlib.Path(arg).exists():          # test a local copy before uploading it
    cells = pathlib.Path(arg).read_text().split("# COMMAND ----------")
else:
    with tempfile.TemporaryDirectory() as d:
        src = pathlib.Path(d) / "nb.py"
        subprocess.run(["databricks", "workspace", "export", NOTEBOOK, "--format", "SOURCE", "--file", str(src),
                        "-p", arg or "datathon"], check=True, capture_output=True)
        cells = src.read_text().split("# COMMAND ----------")

kept, skipped = [], []
for c in cells:
    lines = c.strip("\n").splitlines()
    title = next((l.split(",", 1)[1].strip() for l in lines if l.startswith("# DBTITLE")), "")
    code = [l for l in lines if not l.startswith(("# MAGIC", "# DBTITLE", "# Databricks notebook source"))]
    if not any(l.strip() and not l.lstrip().startswith("#") for l in code):
        continue                                   # markdown-only cell
    (kept if KEEP.match(title) else skipped).append((title, "\n".join(code)))



def definitions_only(code: str) -> str:
    """Drop top-level demo/test statements (prints, loops, calls into the engine) — keep defs, imports, constants."""
    tree = ast.parse(code)
    local_fns = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    def calls_engine(node):
        return any(isinstance(c, ast.Call) and isinstance(c.func, ast.Name) and c.func.id in local_fns
                   for c in ast.walk(node))
    keep = [n for n in tree.body
            if isinstance(n, (ast.FunctionDef, ast.ClassDef, ast.Import, ast.ImportFrom))
            or (isinstance(n, (ast.Assign, ast.AnnAssign)) and not calls_engine(n))]
    return ast.unparse(ast.Module(body=keep, type_ignores=[]))

kept = [(t, definitions_only(c)) for t, c in kept]
OUT.parent.mkdir(exist_ok=True)
header = ('"""AUTO-GENERATED by tools/sync_engine.py from the 06_recommend notebook — do not edit here.\n'
          'Edit the notebook, then re-run the sync."""\n'
          "from engine._spark import spark  # Databricks Connect session supplied by the app\n")
OUT.write_text(header + "\n\n".join(f"# ===== {t} =====\n{c}" for t, c in kept) + "\n")
print("kept:", [t for t, _ in kept])
print("skipped:", [t for t, _ in skipped])
